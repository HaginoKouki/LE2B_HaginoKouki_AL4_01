#pragma once
/*====================================
 *
 * シーンの種類を表す列挙型。
 *
 * 【なぜクラスのポインタではなく列挙型で指定するか】
 * シーンが次のシーンを new して渡す形にすると、TitleScene が GameScene を
 * include することになり、シーン同士が互いを知る関係になる。
 * 種類だけ伝えて、実体の生成は SceneManager::CreateScene() が一手に引き受ける。
 *
 * 【シーンを増やす手順】
 * 1. ここに列挙子を足す.
 * 2. SceneManager::CreateScene() の switch に case を足す.
 * 実体の無い列挙子を先に置いておくと、そこへ遷移した瞬間に何も無い画面になるので、
 * 列挙子とシーンクラスは必ずセットで追加すること.
 *
 * ====================================*/

enum class SceneType {
	Title,
	Game,
};
